class SunsetPrayerDetailsScreen extends StatefulWidget {
  const SunsetPrayerDetailsScreen({Key? key}) : super(key: key);

  @override
  State<SunsetPrayerDetailsScreen> createState() =>
      _SunsetPrayerDetailsScreenState();
}

class _SunsetPrayerDetailsScreenState extends State<SunsetPrayerDetailsScreen> {
  int _selectedIndex = 0;
  final PageController _pageController = PageController();
  final FocusNode _focusNode = FocusNode();
  final List<ScrollController> _scrollControllers = [];

  @override
  void initState() {
    super.initState();
    _scrollControllers.addAll(
      List.generate(sunsetSections.length, (_) => ScrollController()),
    );
    WidgetsBinding.instance.addPostFrameCallback((_) {
      _focusNode.requestFocus();
    });
  }

  @override
  void dispose() {
    _pageController.dispose();
    _focusNode.dispose();
    for (var controller in _scrollControllers) {
      controller.dispose();
    }
    super.dispose();
  }

  void _changePage(int offset) {
    final targetPage = _selectedIndex + offset;
    if (targetPage >= 0 && targetPage < sunsetSections.length) {
      _pageController.animateToPage(
        targetPage,
        duration: const Duration(milliseconds: 300),
        curve: Curves.easeInOut,
      );
    }
  }

  void _scrollContent(double offset) {
    final currentScrollController = _scrollControllers[_selectedIndex];
    if (currentScrollController.hasClients) {
      final target = currentScrollController.offset + offset;
      currentScrollController.animateTo(
        target.clamp(0.0, currentScrollController.position.maxScrollExtent),
        duration: const Duration(milliseconds: 150),
        curve: Curves.easeInOut,
      );
    }
  }

  void _handleKeyEvent(KeyEvent event) {
    if (event is KeyDownEvent) {
      // تفعيل مفتاح F11 لتبديل وضع ملء الشاشة
      if (event.logicalKey == LogicalKeyboardKey.f11) {
        windowManager.isFullScreen().then(
          (isFullScreen) => windowManager.setFullScreen(!isFullScreen),
        );
      } else if (event.logicalKey == LogicalKeyboardKey.arrowLeft) {
        _changePage(1);
      } else if (event.logicalKey == LogicalKeyboardKey.arrowRight) {
        _changePage(-1);
      } else if (event.logicalKey == LogicalKeyboardKey.arrowDown) {
        _scrollContent(120.0);
      } else if (event.logicalKey == LogicalKeyboardKey.arrowUp) {
        _scrollContent(-120.0);
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return KeyboardListener(
      focusNode: _focusNode,
      onKeyEvent: _handleKeyEvent,
      child: Directionality(
        textDirection: TextDirection.rtl,
        child: Scaffold(
          backgroundColor: const Color(0xFF000000),
          body: SafeArea(
            child: Column(
              children: [
                Padding(
                  padding: const EdgeInsets.only(
                    left: 12,
                    right: 12,
                    top: 12,
                    bottom: 8,
                  ),
                  child: Row(
                    children: [
                      IconButton(
                        icon: const Icon(
                          Icons.arrow_back_rounded,
                          color: Color.fromARGB(255, 255, 255, 255),
                          size: 30,
                        ),
                        tooltip: 'رجوع',
                        onPressed: () => Navigator.pop(context),
                      ),
                      Expanded(
                        child: Container(
                          decoration: BoxDecoration(
                            color: const Color.fromARGB(255, 0, 0, 0),
                            borderRadius: BorderRadius.circular(20),
                            border: Border.all(
                              color: const Color.fromARGB(255, 0, 0, 0),
                              width: 1.5,
                            ),
                            boxShadow: [
                              BoxShadow(
                                color: Colors.black.withOpacity(0.3),
                                blurRadius: 10,
                                offset: const Offset(0, 2),
                              ),
                            ],
                          ),
                          child: Padding(
                            padding: const EdgeInsets.symmetric(
                              horizontal: 16,
                              vertical: 4,
                            ),
                            child: DropdownButtonHideUnderline(
                              child: DropdownButton<String>(
                                value: sunsetSections[_selectedIndex].id,
                                isExpanded: true,
                                icon: const Icon(
                                  Icons.arrow_drop_down_rounded,
                                  color: Color.fromARGB(255, 255, 255, 255),
                                  size: 30,
                                ),
                                dropdownColor: const Color.fromARGB(
                                  255,
                                  0,
                                  0,
                                  0,
                                ),
                                style: const TextStyle(
                                  fontSize: 16,
                                  fontWeight: FontWeight.bold,
                                  color: Colors.white,
                                  fontFamily: 'Cairo',
                                ),
                                items: sunsetSections.map((section) {
                                  return DropdownMenuItem<String>(
                                    value: section.id,
                                    child: Text(
                                      section.title,
                                      style: const TextStyle(
                                        fontSize: 15,
                                        fontWeight: FontWeight.bold,
                                        fontFamily: 'Cairo',
                                      ),
                                    ),
                                  );
                                }).toList(),
                                onChanged: (String? newId) {
                                  if (newId != null) {
                                    final newIndex = sunsetSections.indexWhere(
                                      (section) => section.id == newId,
                                    );
                                    _pageController.animateToPage(
                                      newIndex,
                                      duration: const Duration(
                                        milliseconds: 300,
                                      ),
                                      curve: Curves.easeInOut,
                                    );
                                  }
                                },
                              ),
                            ),
                          ),
                        ),
                      ),
                    ],
                  ),
                ),
                Expanded(
                  child: PageView.builder(
                    controller: _pageController,
                    physics: const BouncingScrollPhysics(),
                    onPageChanged: (index) {
                      setState(() {
                        _selectedIndex = index;
                      });
                    },
                    itemCount: sunsetSections.length,
                    itemBuilder: (context, index) {
                      final section = sunsetSections[index];

                      return SingleChildScrollView(
                        controller: _scrollControllers[index],
                        physics: const BouncingScrollPhysics(),
                        padding: const EdgeInsets.symmetric(
                          horizontal: 16,
                          vertical: 12,
                        ),
                        child: Container(
                          width: double.infinity,
                          padding: const EdgeInsets.symmetric(
                            horizontal: 20,
                            vertical: 28,
                          ),
                          decoration: BoxDecoration(
                            color: const Color.fromARGB(255, 0, 0, 0),
                            borderRadius: BorderRadius.circular(24),
                            border: Border.all(
                              color: const Color.fromARGB(255, 0, 0, 0),
                              width: 1.5,
                            ),
                          ),
                          child: Column(
                            crossAxisAlignment: CrossAxisAlignment.center,
                            children: [
                              Text(
                                section.title,
                                style: const TextStyle(
                                  fontSize: 26,
                                  fontWeight: FontWeight.w900,
                                  color: Color.fromARGB(255, 255, 255, 255),
                                  letterSpacing: 1.1,
                                ),
                                textAlign: TextAlign.center,
                              ),
                              const SizedBox(height: 12),
                              Container(
                                width: 80,
                                height: 2,
                                color: const Color.fromARGB(
                                  255,
                                  255,
                                  255,
                                  255,
                                ).withOpacity(0.3),
                              ),
                              const SizedBox(height: 24),
                            ],
                          ),
                        ),
                      );
                    },
                  ),
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }
}
